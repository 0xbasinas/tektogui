#!/usr/bin/env node
// Keep the public JSX declarations in step with the component schema.
import { readFileSync, writeFileSync } from "node:fs";

const schema = JSON.parse(readFileSync(new URL("../src/components.json", import.meta.url), "utf8"));
const target = new URL("../src/jsx-types.d.ts", import.meta.url);
const lines = ["// Generated by scripts/generate-jsx-types.js. Do not edit by hand.", "import type { TektoElement } from './index.js';", "export namespace JSX {", "  interface IntrinsicElements {"];
for (const component of schema.components) {
  lines.push(`    ${component.name}: {`);
  for (const prop of [...component.props, ...(component.jsxProps || [])]) {
    const type = prop.jsxType || prop.type;
    if (!type || type === "function" || type === "object") throw new Error(`missing JSX type for ${component.name}.${prop.name}`);
    lines.push(`      ${prop.name}${prop.required ? "" : "?"}: ${type};`);
  }
  lines.push("      children?: unknown;", "    };");
}
lines.push("  }", "}", "");
const output = lines.join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("JSX types are stale; run node packages/jsx-runtime/scripts/generate-jsx-types.js");
} else {
  writeFileSync(target, output);
}
